/**
 * Returns a 4-image multi-angle set for a product:
 * 1. Front View (Primary full framing)
 * 2. Side / Angle Perspective
 * 3. Craftsmanship & Texture Detail Close-up
 * 4. In-Room Context / Setting View
 */
export function getProductMultiAngleImages(primaryUrl: string): string[] {
  if (!primaryUrl) return [];
  const extIndex = primaryUrl.lastIndexOf('.');
  if (extIndex === -1) return [primaryUrl];
  const prefix = primaryUrl.slice(0, extIndex);
  const ext = primaryUrl.slice(extIndex);
  return [
    primaryUrl,
    `${prefix}_angle${ext}`,
    `${prefix}_detail${ext}`,
    `${prefix}_context${ext}`,
  ];
}

